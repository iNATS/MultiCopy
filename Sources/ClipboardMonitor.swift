import AppKit

/// Watches the general pasteboard by polling its change counter, which is cheap and reads no
/// content. Data is read only when something new was copied.
final class ClipboardMonitor: NSObject {
    var isPaused = false
    let pasteboard: NSPasteboard

    private let store: HistoryStore
    private let extraIgnoredApps: Set<String>
    private var lastChangeCount = -1
    private var timer: Timer?

    /// Largest entry kept in full; bigger copies keep only their text, or are skipped.
    private static let maxEntryBytes = 16 << 20

    /// The only pasteboard types stored. App-private formats are ignored to keep memory low.
    private static let storedTypes: [NSPasteboard.PasteboardType] = [
        .string, .rtf, .rtfd, .html, .URL, .fileURL, .png, .tiff,
    ]
    private static let heavyTypes: Set<NSPasteboard.PasteboardType> = [.rtfd, .png, .tiff]

    /// Markers (see nspasteboard.org) that password managers and other apps put on data
    /// that must not be recorded.
    private static let privateMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    /// Apps whose copies are never recorded, even if they forget to mark them.
    private static let ignoredApps: Set<String> = [
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "org.keepassxc.keepassxc",
        "com.lastpass.LastPass",
        "in.sinew.Enpass-Desktop",
    ]

    init(store: HistoryStore, extraIgnoredApps: Set<String>, pasteboard: NSPasteboard = .general) {
        self.store = store
        self.extraIgnoredApps = extraIgnoredApps
        self.pasteboard = pasteboard
    }

    func start() {
        let timer = Timer(timeInterval: 0.5, target: self, selector: #selector(poll), userInfo: nil, repeats: true)
        timer.tolerance = 0.2 // lets macOS batch wake-ups to save energy
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        poll()
    }

    /// Call after MultiCopy itself writes to the pasteboard so that write isn't recorded again.
    func skipCurrentContents() {
        lastChangeCount = pasteboard.changeCount
    }

    @objc func poll() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount
        guard !isPaused, let item = capture() else { return }
        store.add(item)
    }

    private func capture() -> ClipItem? {
        guard let pasteboardItems = pasteboard.pasteboardItems, !pasteboardItems.isEmpty else { return nil }

        let allTypes = Set(pasteboardItems.flatMap { $0.types.map(\.rawValue) })
        guard allTypes.isDisjoint(with: Self.privateMarkers) else { return nil }

        let frontApp = NSWorkspace.shared.frontmostApplication
        let sourceID = pasteboard.string(forType: .init("org.nspasteboard.source")) ?? frontApp?.bundleIdentifier
        if let sourceID, Self.ignoredApps.contains(sourceID) || extraIgnoredApps.contains(sourceID) {
            return nil
        }

        var contents: ClipItem.Contents = []
        for pasteboardItem in pasteboardItems.prefix(500) {
            let types = Set(pasteboardItem.types)
            let hasText = types.contains(.string) || types.contains(.fileURL)
            var entry: [NSPasteboard.PasteboardType: Data] = [:]
            for type in Self.storedTypes where types.contains(type) {
                // Text and files don't need the preview images some apps attach; PNG beats TIFF.
                if hasText && (type == .png || type == .tiff) { continue }
                if type == .tiff && types.contains(.png) { continue }
                entry[type] = pasteboardItem.data(forType: type)
            }
            if !entry.isEmpty { contents.append(entry) }
        }
        return ClipItem(contents: Self.fitToBudget(contents), sourceApp: frontApp?.localizedName)
    }

    private static func fitToBudget(_ contents: ClipItem.Contents) -> ClipItem.Contents {
        func size(_ contents: ClipItem.Contents) -> Int {
            contents.reduce(0) { total, entry in total + entry.values.reduce(0) { $0 + $1.count } }
        }
        guard size(contents) > maxEntryBytes else { return contents }
        let light = contents
            .map { $0.filter { !heavyTypes.contains($0.key) } }
            .filter { !$0.isEmpty }
        return size(light) <= maxEntryBytes ? light : []
    }
}
